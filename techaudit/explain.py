def metric_help(mid: str, label: str = "", criterion: str = "") -> dict:
    """{'what','why','fix'} для метрики/проверки/теста адреса; пустые поля, если пояснения нет."""
    if mid in METRIC_HELP:
        w, y, f = METRIC_HELP[mid]
        return {"what": w, "why": y, "fix": f}
    if mid.startswith("probe:"):
        k = mid[6:]
        return {"what": probe_what(k) or "Тест адреса данного вида.",
                "why": "Показывает, какая доля адресов этого вида отработала так, как ожидается.",
                "fix": "Скачайте список непрошедших адресов и передайте разработке: у каждого указан фактический ответ."}
    if mid.startswith("block:"):
        return {"what": BLOCK_HELP.get(mid[6:], "Доля пройденных проверок блока."), "why": "Балл блока = пройдено ÷ оценённые проверки.",
                "fix": "Откройте блок: пункты отсортированы от худших к лучшим."}
    if mid.startswith("check:"):
        return {"what": criterion or label, "why": "Доля адресов, прошедших проверку (если по пункту нет разбивки — 100 / 50 / 0 по статусу).",
                "fix": "Скачайте список непрошедших URL и откройте «Как проверить»."}
    if mid.startswith("crawl_"):
        return {"what": label, "why": "Данные берутся из выгрузки Screaming Frog (Internal → All).", "fix": "Откройте страницу краула: там фильтры и выгрузка URL."}
    return {"what": "", "why": "", "fix": ""}


def block_help(name: str) -> str:
    return BLOCK_HELP.get(name, "")
